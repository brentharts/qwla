#!/usr/bin/env python3
"""
Anyonic entanglement entropy of regions of cone points in the level-k ground state (ROADMAP Stage 9l).

At level k the 12 punctures are SU(2)_k anyons of charge 1/2 (qdeform_punctures.py, Stage 9c); the state space is not
a tensor product, so the entropy of a region needs the anyonic definition. For a disc A that holds m punctures, the
operators of A form the Temperley-Lieb algebra TL_A generated by the e of neighbouring punctures in A. It is a sum of
matrix algebras, one per total charge c of A, and the space splits as  sum_c C^{n_c} (x) C^{n'_c}. With p_c the weight
of the ground state in sector c and rho_c its normalised reduced state on C^{n_c},

    S(A) = sum_c p_c [ -ln p_c + S(rho_c) + ln d_c ],        d_c = sin((2c+1) pi/(k+2)) / sin(pi/(k+2)),

the entropy defined with the quantum trace (Bonderson, Knapp and Patel 2017, as recalled; not re-read for this script).
At k = infinity d_c = 2c+1 and S is the ordinary entropy of the spins; at k = 2 it is the Gaussian Majorana entropy
with (1/2) ln 2 for an unpaired mode. Both limits are tested below against independent computations.

Regions: the discs are the arcs of consecutive punctures along the Hamiltonian cycle that orders the punctures (the
disc is a neighbourhood of the arc), for two Hamiltonian cycles: 66 bipartitions each. Other sets of punctures need a
choice of disc and are not treated.

The sectors are found numerically, without Jones-Wenzl projectors: a generic Hermitian X in TL_A has each eigenvalue
with multiplicity n'_c; a second generic element links the eigenvalues of one sector; matrix units built from it give
rho_c. A sector is identified with its charge by (n_c, n'_c), the numbers of fusion paths, and by the trace of one
generator where those tie.

The entropy splits as  S = <L> + S_bulk  with  L = sum_c ln d_c (projector on charge c), an operator in the centre of
the region's algebra, and S_bulk = sum_c p_c [ -ln p_c + S(rho_c) ]: the form of an entropy with an area operator in the
centre (Stage 9m). Both parts are fitted separately.

Usage: python3 anyon_entropy.py [--tests]       (about a minute)
"""
import itertools
import json
import math
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import qdeform_punctures as QD  # noqa: E402
import null_cone_level2 as L2  # noqa: E402

N = 12
LEVELS = (2, 3, 4, 5, 6, 8, 10, 20, 50, None)


def paths(k, m):
    """Number of fusion paths of m charge-1/2 anyons to total charge t/2, for t = 0..K (K = k, or m when k is None)."""
    K = m if k is None else k
    v = np.zeros(K + 1); v[0] = 1
    for _ in range(m):
        w = np.zeros(K + 1)
        w[1:] += v[:-1]; w[:-1] += v[1:]
        v = w
    return v.astype(int)


def qdim(k, t):
    return float(t + 1) if k is None else math.sin((t + 1) * math.pi / (k + 2)) / math.sin(math.pi / (k + 2))


class Level:
    def __init__(self, k, cycle, E, F):
        self.k = k
        A = 1j if k is None else QD.A_of_level(k)
        m = QD.Model(A, cycle, E, F)
        w, U = np.linalg.eigh(m.G)
        keep = w > 1e-8 * w.max()
        assert not (w < -1e-8 * w.max()).any()
        self.D = int(keep.sum())
        s = np.sqrt(w[keep]); Q = U[:, keep]
        self.to = lambda O: (s[:, None] * (Q.T @ O @ Q)) / s[None, :]
        self.e = [self.to(x) for x in m.e]
        self.dval = m.d
        assert max(np.abs(x - x.conj().T).max() for x in self.e) < 1e-7
        H = self.to(m.hamiltonian())
        assert np.abs(H - H.conj().T).max() < 1e-6
        ev, vec = np.linalg.eigh((H + H.conj().T) / 2)
        assert ev[1] - ev[0] > 1e-6 or self.D == 1
        self.E0 = float(ev[0]); self.psi = vec[:, 0]
        self.cycle = list(cycle)

    def generic(self, gens, rng):
        D = self.D
        X = np.zeros((D, D), complex)
        for g in gens:                                     # every generator, plus short random words (long words have low rank)
            X += rng.normal() * g
        for _ in range(4 * len(gens)):
            W = np.eye(D, dtype=complex)
            for _ in range(rng.integers(2, 4)):
                W = W @ gens[rng.integers(len(gens))]
            X += rng.normal() * W
        return (X + X.conj().T) / 2

    def entropy(self, i, m, seed=0):
        """Anyonic entropy of the arc of positions i .. i+m-1, and its sector table."""
        rng = np.random.default_rng(1000 * seed + 13 * i + m)
        D, psi, k = self.D, self.psi, self.k
        gens = self.e[i:i + m - 1]
        if not gens:
            X = np.zeros((D, D), complex); X2 = X
        else:
            X = self.generic(gens, rng); X2 = self.generic(gens, rng)
        ev, U = np.linalg.eigh(X)
        groups = [[0]]
        for a in range(1, D):
            (groups[-1].append(a) if ev[a] - ev[a - 1] < 1e-7 else groups.append([a]))
        Us = [U[:, g] for g in groups]
        ng = len(groups)
        link = np.array([[np.linalg.norm(Us[a].conj().T @ X2 @ Us[b]) > 1e-5 for b in range(ng)] for a in range(ng)])
        comp = [-1] * ng; nc = 0
        for a in range(ng):
            if comp[a] < 0:
                st = [a]; comp[a] = nc
                while st:
                    u = st.pop()
                    for v in range(ng):
                        if link[u, v] and comp[v] < 0:
                            comp[v] = nc; st.append(v)
                nc += 1
        nA, nB = paths(k, m), paths(k, N - m)
        S, table, tot = 0.0, [], 0
        for c in range(nc):
            mem = [a for a in range(ng) if comp[a] == c]
            n, npr = len(mem), len(groups[mem[0]])
            assert all(len(groups[a]) == npr for a in mem)
            tot += n * npr
            cand = [t for t in range(len(nA)) if nA[t] == n and nB[t] == npr and (t - m) % 2 == 0]
            if gens and len({round(qdim(k, t), 9) for t in cand}) > 1:     # tie: use tr(e) = d n' x (paths of m-2 to the same charge)
                tr = sum(np.trace(Us[a].conj().T @ gens[0] @ Us[a]).real for a in mem) / (self.dval * npr)
                nA2 = paths(k, m - 2)
                cand = [t for t in cand if abs(nA2[t] - tr) < 1e-6]
            ds = sorted({round(qdim(k, t), 9) for t in cand})
            assert len(ds) == 1, (k, i, m, n, npr, cand)
            d = ds[0]
            a0 = mem[0]
            V = []
            for a in mem:                                  # partial isometries from the reference eigenspace a0 to a
                if a == a0:
                    V.append(Us[a0] @ Us[a0].conj().T); continue
                Wm = Us[a].conj().T @ X2 @ Us[a0]          # = x times a unitary npr x npr
                x2 = np.trace(Wm.conj().T @ Wm).real / npr
                assert x2 > 1e-12 and np.abs(Wm.conj().T @ Wm - x2 * np.eye(npr)).max() < 1e-6 * max(1, x2)
                V.append(Us[a] @ Wm @ Us[a0].conj().T / math.sqrt(x2))
            comps = np.array([v.conj().T @ psi for v in V])     # rows: psi's component in block a, carried to a0
            rho = comps @ comps.conj().T
            p = float(np.trace(rho).real)
            if p < 1e-13:
                table.append(dict(t=cand[0], n=n, n_prime=npr, d=d, p=0.0)); continue
            lam = np.linalg.eigvalsh(rho / p); lam = lam[lam > 1e-14]
            Sc = float(-(lam * np.log(lam)).sum())
            S += p * (-math.log(p) + Sc + math.log(d))
            table.append(dict(t=cand[0], n=n, n_prime=npr, d=d, p=p, S_rho=Sc))
        assert tot == D, (tot, D)
        assert abs(sum(r["p"] for r in table) - 1) < 1e-8
        return S, table


def spin_entropy(E):
    """Ordinary entropies of the Heisenberg ground state (independent of the pairing basis), as a function of a set."""
    states = [b for b in range(1 << N) if bin(b).count("1") == N // 2]
    idx = {b: a for a, b in enumerate(states)}
    H = np.zeros((len(states), len(states)))
    for a, b in enumerate(states):
        for i, j in E:
            bi, bj = (b >> i) & 1, (b >> j) & 1
            if bi == bj:
                H[a, a] += 0.25
            else:
                H[a, a] -= 0.25
                H[idx[b ^ (1 << i) ^ (1 << j)], a] += 0.5
    ev, vec = np.linalg.eigh(H)
    psi = np.zeros(1 << N); psi[states] = vec[:, 0]

    def S(R):
        R = sorted(R); Rc = [p for p in range(N) if p not in R]
        T = psi.reshape([2] * N).transpose([N - 1 - p for p in R] + [N - 1 - p for p in Rc]).reshape(1 << len(R), -1)
        s = np.linalg.svd(T, compute_uv=False) ** 2; s = s[s > 1e-15]
        return float(-(s * np.log(s)).sum())
    return float(ev[0]), S


def fit(rows):
    X = np.array([[c, m, 1.0] for m, c, S in rows]); y = np.array([S for *_, S in rows])
    co = np.linalg.lstsq(X, y, rcond=None)[0]
    r2 = 1 - ((y - X @ co) ** 2).sum() / ((y - y.mean()) ** 2).sum()
    c1 = np.linalg.lstsq(X[:, 1:], y, rcond=None)[0]
    r2s = 1 - ((y - X[:, 1:] @ c1) ** 2).sum() / ((y - y.mean()) ** 2).sum()
    return dict(per_cut_edge=float(co[0]), per_puncture=float(co[1]), const=float(co[2]), R2_cut_and_size=float(r2), R2_size_only=float(r2s), regions=len(rows))


def main():
    V, E, F = QD.icosa()
    cycles = QD.hamiltonian_cycles(E, 2)
    E0s, Sspin = spin_entropy(E)
    a = L2.signed_adjacency(L2.icosahedron()[1])[0]; G2 = a / 5 ** 0.5
    out = dict(levels=[], cycles=[list(map(int, c)) for c in cycles])
    arcs = [(ci, i, m) for ci in range(2) for m in range(1, N) for i in range(N - m + 1)]
    for k in LEVELS:
        models = [Level(k, c, E, F) for c in cycles]
        assert abs(models[0].E0 - models[1].E0) < 1e-6
        ent = {}
        for ci, i, m in arcs:
            S, tab = models[ci].entropy(i, m)
            R = frozenset(cycles[ci][i:i + m])
            ent[(ci, i, m)] = (R, S, tab)
        # tests: an arc and its complement (two independent computations); the two exact limits
        worst_c = 0.0
        for (ci, i, m), (R, S, tab) in ent.items():
            if i == 0 and m < N:
                worst_c = max(worst_c, abs(S - ent[(ci, m, N - m)][1]))
        assert worst_c < 1e-6, (k, worst_c)
        if k is None:
            assert abs(models[0].E0 - E0s) < 1e-8
            assert max(abs(S - Sspin(R)) for R, S, _ in ent.values()) < 1e-6
        if k == 2:
            assert max(abs(S - L2.entropy(G2, sorted(R))) for R, S, _ in ent.values()) < 1e-6
        # one row per bipartition and disc: keep the smaller side; the same vertex set from the two cycles is compared
        rows, seen, twice = [], {}, []
        rows_area, rows_bulk = [], []
        for (ci, i, m), (R, S, tab) in sorted(ent.items()):
            key = R if (len(R) < 6 or (len(R) == 6 and 0 in R)) else frozenset(range(N)) - R
            if (ci, key) in seen:
                continue
            seen[(ci, key)] = S
            if ci == 1 and (0, key) in seen:
                twice.append(abs(S - seen[(0, key)])); continue
            cut = sum((p in key) != (q in key) for p, q in E)
            rows.append((len(key), cut, S))
            area = sum(r['p'] * math.log(r['d']) for r in tab if r['p'] > 0)
            rows_area.append((len(key), cut, area)); rows_bulk.append((len(key), cut, S - area))
        f = fit(rows)
        fa, fb = fit(rows_area), fit(rows_bulk)
        share = float(np.mean([a[2] / r[2] for a, r in zip(rows_area, rows)]))
        by = {}
        for m in range(1, 7):
            sub = [S for mm, c, S in rows if mm == m]
            by[m] = dict(n=len(sub), S_mean=float(np.mean(sub)), S_min=float(min(sub)), S_max=float(max(sub)))
        rec = dict(level=k if k is not None else "classical", dim=models[0].D, E0=models[0].E0, fit=f, by_size=by,
                   same_set_two_cycles=dict(n=len(twice), max_difference=float(max(twice)) if twice else None),
                   complement_check=worst_c, fit_area_term=fa, fit_bulk_term=fb, mean_area_share=share, S_one=by[1]["S_mean"], ln_d=math.log(qdim(k, 1)))
        out["levels"].append(rec)
        print("k=%-9s dim=%3d  per edge %.4f  per puncture %.4f  const %+.4f  R2 %.3f (size only %.3f)  regions %d   S(1)=%.4f  max S(6)=%.4f  two-cycle diff %s" % (
            rec["level"], rec["dim"], f["per_cut_edge"], f["per_puncture"], f["const"], f["R2_cut_and_size"], f["R2_size_only"], f["regions"],
            by[1]["S_mean"], by[6]["S_max"], rec["same_set_two_cycles"]))
        print("    area term <ln d_c>: per edge %.4f per puncture %.4f R2 %.3f | bulk term: per edge %.4f per puncture %.4f R2 %.3f | mean share of area term %.3f" % (
            fa["per_cut_edge"], fa["per_puncture"], fa["R2_cut_and_size"], fb["per_cut_edge"], fb["per_puncture"], fb["R2_cut_and_size"], share))
    json.dump(out, open(os.path.join(HERE, "anyon_entropy.json"), "w"), indent=1)
    if "--tests" in sys.argv:
        print("anyon_entropy: all tests passed (arc = complement at every level; k = 2 equals the Majorana formula; classical equals the spin entropy)")


if __name__ == "__main__":
    main()
